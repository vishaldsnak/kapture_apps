package com.mazda.gms3.dmt.vo;

public class UserGroupDetails {

	private String userGroupName=null;
	private String userGroupRefKey=null;
	private String userGroupGuid=null;
	
	
	public String getUserGroupGuid() {
		return userGroupGuid;
	}
	public void setUserGroupGuid(String userGroupGuid) {
		this.userGroupGuid = userGroupGuid;
	}
	public String getUserGroupName() {
		return userGroupName;
	}
	public void setUserGroupName(String userGroupName) {
		this.userGroupName = userGroupName;
	}
	public String getUserGroupRefKey() {
		return userGroupRefKey;
	}
	public void setUserGroupRefKey(String userGroupRefKey) {
		this.userGroupRefKey = userGroupRefKey;
	}
	
	
}
