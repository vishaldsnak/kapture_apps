package com.mazda.gms3.dmt.vo;

import java.io.File;

public class ChildModelFolderDetails {
	
	private String year=null;
	private String alphabet=null;
	private File childModelFolder=null;
	public String getYear() {
		return year;
	}
	public void setYear(String year) {
		this.year = year;
	}
	public String getAlphabet() {
		return alphabet;
	}
	public void setAlphabet(String alphabet) {
		this.alphabet = alphabet;
	}
	public File getChildModelFolder() {
		return childModelFolder;
	}
	public void setChildModelFolder(File childModelFolder) {
		this.childModelFolder = childModelFolder;
	}
	
	
	

}
